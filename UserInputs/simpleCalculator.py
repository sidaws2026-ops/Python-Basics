first_number = int(input("Enter first number: "))
second_number = int(input("Enter second number: "))
print("First number: ")
print(first_number)
print("Second number: ")
print(second_number)

# Addition
total_number = first_number + second_number
print("Sum of two numers: ")
print(total_number)
# Substraction
total_number = first_number - second_number
print("Substraction of two numers: ")
print(total_number)

